-- =========================================================
-- DATABASE : go_kantin
-- DBMS     : PostgreSQL
-- PURPOSE  : Migration awal struktur database Sistem Kantin
-- =========================================================

-- Langkah 1
-- Buat database terlebih dahulu secara terpisah.
-- Jalankan perintah berikut melalui pgAdmin Query Tool pada database postgres, atau melalui psql:
-- CREATE DATABASE go_kantin;
-- Setelah database berhasil dibuat, koneksikan ke database
-- go_kantin, kemudian jalankan seluruh file migration ini.

-- Contoh:
-- psql -U postgres -d go_kantin -f database/001_ddl_script.sql

-- LANGKAH 2:
-- RESET STRUKTUR DATABASE 
-- PERINGATAN: Semua tabel dan data terkait akan dihapus.

BEGIN;
DROP TABLE IF EXISTS stok_log CASCADE;
DROP TABLE IF EXISTS log_aktivitas CASCADE;
DROP TABLE IF EXISTS notifikasi CASCADE;
DROP TABLE IF EXISTS pembayaran CASCADE;
DROP TABLE IF EXISTS detail_transaksi CASCADE;
DROP TABLE IF EXISTS transaksi CASCADE;
DROP TABLE IF EXISTS detail_keranjang CASCADE;
DROP TABLE IF EXISTS keranjang CASCADE;
DROP TABLE IF EXISTS varian_produk CASCADE;
DROP TABLE IF EXISTS produk CASCADE;
DROP TABLE IF EXISTS kategori_produk CASCADE;
DROP TABLE IF EXISTS profil_penjual CASCADE;
DROP TABLE IF EXISTS kategori_penjual CASCADE;
DROP TABLE IF EXISTS metode_pembayaran CASCADE;
DROP TABLE IF EXISTS pengaturan_sistem CASCADE;
DROP TABLE IF EXISTS role_permissions CASCADE;
DROP TABLE IF EXISTS user_roles CASCADE;
DROP TABLE IF EXISTS permissions CASCADE;
DROP TABLE IF EXISTS roles CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- Hapus function trigger jika sudah pernah dibuat.
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;
-- =========================================================
-- 1. USERS
-- Semua akun: pembeli, admin penjual, dan super admin
-- =========================================================

CREATE TABLE users (
    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) UNIQUE,
    password_hash VARCHAR(255) NOT NULL,

    status_akun VARCHAR(20) NOT NULL DEFAULT 'aktif'
        CHECK (
            status_akun IN (
                'aktif',
                'pending',
                'ditolak',
                'nonaktif'
            )
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 2. ROLES
-- =========================================================

CREATE TABLE roles (
    id_role BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_role VARCHAR(50) NOT NULL UNIQUE,
    deskripsi VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 3. PERMISSIONS
-- =========================================================

CREATE TABLE permissions (
    id_permission BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_permission VARCHAR(100) NOT NULL UNIQUE,
    deskripsi VARCHAR(255)
);

-- =========================================================
-- 4. USER_ROLES
-- Relasi many-to-many antara users dan roles
-- =========================================================

CREATE TABLE user_roles (
    id_user BIGINT NOT NULL,
    id_role BIGINT NOT NULL,

    PRIMARY KEY (id_user, id_role),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (id_user)
        REFERENCES users(id_user)
        ON DELETE CASCADE,

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (id_role)
        REFERENCES roles(id_role)
        ON DELETE RESTRICT
);

-- =========================================================
-- 5. ROLE_PERMISSIONS
-- Relasi many-to-many antara roles dan permissions
-- =========================================================

CREATE TABLE role_permissions (
    id_role BIGINT NOT NULL,
    id_permission BIGINT NOT NULL,

    PRIMARY KEY (id_role, id_permission),

    CONSTRAINT fk_role_permissions_role
        FOREIGN KEY (id_role)
        REFERENCES roles(id_role)
        ON DELETE CASCADE,

    CONSTRAINT fk_role_permissions_permission
        FOREIGN KEY (id_permission)
        REFERENCES permissions(id_permission)
        ON DELETE CASCADE
);

-- =========================================================
-- 6. KATEGORI_PENJUAL
-- =========================================================

CREATE TABLE kategori_penjual (
    id_kategori_penjual BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL UNIQUE,
    deskripsi VARCHAR(255)
);

-- =========================================================
-- 7. PROFIL_PENJUAL
-- Data usaha terpisah dari data autentikasi
-- =========================================================

CREATE TABLE profil_penjual (
    id_profil_penjual BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_user BIGINT NOT NULL UNIQUE,
    nama_usaha VARCHAR(100) NOT NULL,
    id_kategori_penjual BIGINT,
    no_hp VARCHAR(20),
    alamat TEXT,

    disetujui_oleh BIGINT,
    tgl_konfirmasi TIMESTAMPTZ,
    catatan_penolakan VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_profil_penjual_user
        FOREIGN KEY (id_user)
        REFERENCES users(id_user)
        ON DELETE RESTRICT,

    CONSTRAINT fk_profil_penjual_kategori
        FOREIGN KEY (id_kategori_penjual)
        REFERENCES kategori_penjual(id_kategori_penjual)
        ON DELETE SET NULL,

    CONSTRAINT fk_profil_penjual_penyetuju
        FOREIGN KEY (disetujui_oleh)
        REFERENCES users(id_user)
        ON DELETE SET NULL
);

-- =========================================================
-- 8. KATEGORI_PRODUK
-- =========================================================

CREATE TABLE kategori_produk (
    id_kategori_produk BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    nama_kategori VARCHAR(100) NOT NULL UNIQUE,
    deskripsi VARCHAR(255),
    status_aktif BOOLEAN NOT NULL DEFAULT TRUE
);

-- =========================================================
-- 9. PRODUK
-- =========================================================

CREATE TABLE produk (
    id_produk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profil_penjual BIGINT NOT NULL,
    id_kategori_produk BIGINT NOT NULL,

    nama_produk VARCHAR(150) NOT NULL,
    deskripsi TEXT,
    gambar VARCHAR(255),

    status_produk VARCHAR(20) NOT NULL DEFAULT 'aktif'
        CHECK (
            status_produk IN (
                'aktif',
                'nonaktif',
                'habis'
            )
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_produk_penjual
        FOREIGN KEY (id_profil_penjual)
        REFERENCES profil_penjual(id_profil_penjual)
        ON DELETE RESTRICT,

    CONSTRAINT fk_produk_kategori
        FOREIGN KEY (id_kategori_produk)
        REFERENCES kategori_produk(id_kategori_produk)
        ON DELETE RESTRICT
);

CREATE INDEX idx_produk_penjual
    ON produk(id_profil_penjual);

CREATE INDEX idx_produk_kategori
    ON produk(id_kategori_produk);

CREATE INDEX idx_produk_status
    ON produk(status_produk);

-- =========================================================
-- 10. VARIAN_PRODUK
-- Harga dan stok setiap varian
-- =========================================================

CREATE TABLE varian_produk (
    id_varian_produk BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_produk BIGINT NOT NULL,
    nama_varian VARCHAR(100) NOT NULL,

    harga_satuan NUMERIC(12,2) NOT NULL
        CHECK (harga_satuan >= 0),

    stok INTEGER NOT NULL DEFAULT 0
        CHECK (stok >= 0),

    batas_stok_minimum INTEGER NOT NULL DEFAULT 0
        CHECK (batas_stok_minimum >= 0),

    status_aktif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_varian_produk
        UNIQUE (id_produk, nama_varian),

    CONSTRAINT fk_varian_produk_produk
        FOREIGN KEY (id_produk)
        REFERENCES produk(id_produk)
        ON DELETE RESTRICT
);

-- =========================================================
-- 11. KERANJANG
-- Satu keranjang aktif per pengguna
-- =========================================================

CREATE TABLE keranjang (
    id_keranjang BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_user BIGINT NOT NULL UNIQUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_keranjang_user
        FOREIGN KEY (id_user)
        REFERENCES users(id_user)
        ON DELETE CASCADE
);

-- =========================================================
-- 12. DETAIL_KERANJANG
-- =========================================================

CREATE TABLE detail_keranjang (
    id_detail_keranjang BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_keranjang BIGINT NOT NULL,
    id_varian_produk BIGINT NOT NULL,

    jumlah INTEGER NOT NULL CHECK (jumlah > 0),

    CONSTRAINT uq_keranjang_varian
        UNIQUE (id_keranjang, id_varian_produk),

    CONSTRAINT fk_detail_keranjang_keranjang
        FOREIGN KEY (id_keranjang)
        REFERENCES keranjang(id_keranjang)
        ON DELETE CASCADE,

    CONSTRAINT fk_detail_keranjang_varian
        FOREIGN KEY (id_varian_produk)
        REFERENCES varian_produk(id_varian_produk)
        ON DELETE RESTRICT
);

-- =========================================================
-- 13. TRANSAKSI
-- Satu pesanan hanya untuk satu penjual
-- =========================================================

CREATE TABLE transaksi (
    id_transaksi BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kode_transaksi VARCHAR(40) NOT NULL UNIQUE,

    id_pembeli BIGINT NOT NULL,
    id_profil_penjual BIGINT NOT NULL,

    tgl_transaksi TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    total_produk INTEGER NOT NULL DEFAULT 0
        CHECK (total_produk >= 0),

    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (subtotal >= 0),

    biaya_layanan NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (biaya_layanan >= 0),

    total_harga NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (total_harga >= 0),

    status_transaksi VARCHAR(30) NOT NULL
        DEFAULT 'menunggu_pembayaran'
        CHECK (
            status_transaksi IN (
                'menunggu_pembayaran',
                'dibayar',
                'diproses',
                'siap_diambil',
                'selesai',
                'dibatalkan'
            )
        ),

    catatan_pembeli VARCHAR(500),
    waktu_selesai TIMESTAMPTZ,

    CONSTRAINT fk_transaksi_pembeli
        FOREIGN KEY (id_pembeli)
        REFERENCES users(id_user)
        ON DELETE RESTRICT,

    CONSTRAINT fk_transaksi_penjual
        FOREIGN KEY (id_profil_penjual)
        REFERENCES profil_penjual(id_profil_penjual)
        ON DELETE RESTRICT
);

CREATE INDEX idx_transaksi_pembeli_tanggal
    ON transaksi(id_pembeli, tgl_transaksi DESC);

CREATE INDEX idx_transaksi_penjual_status
    ON transaksi(id_profil_penjual, status_transaksi);

CREATE INDEX idx_transaksi_status
    ON transaksi(status_transaksi);

-- =========================================================
-- 14. DETAIL_TRANSAKSI
-- Snapshot nama dan harga saat pembelian
-- =========================================================

CREATE TABLE detail_transaksi (
    id_detail_transaksi BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_transaksi BIGINT NOT NULL,
    id_varian_produk BIGINT NOT NULL,

    nama_produk_snapshot VARCHAR(150) NOT NULL,
    nama_varian_snapshot VARCHAR(100) NOT NULL,

    jumlah INTEGER NOT NULL CHECK (jumlah > 0),

    harga_satuan NUMERIC(12,2) NOT NULL
        CHECK (harga_satuan >= 0),

    sub_total NUMERIC(12,2) NOT NULL
        CHECK (sub_total >= 0),

    CONSTRAINT fk_detail_transaksi_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES transaksi(id_transaksi)
        ON DELETE RESTRICT,

    CONSTRAINT fk_detail_transaksi_varian
        FOREIGN KEY (id_varian_produk)
        REFERENCES varian_produk(id_varian_produk)
        ON DELETE RESTRICT
);

CREATE INDEX idx_detail_transaksi_transaksi
    ON detail_transaksi(id_transaksi);

-- =========================================================
-- 15. METODE_PEMBAYARAN
-- =========================================================

CREATE TABLE metode_pembayaran (
    id_metode_pembayaran BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kode_metode VARCHAR(50) NOT NULL UNIQUE,
    nama_metode VARCHAR(100) NOT NULL,

    tipe_metode VARCHAR(30) NOT NULL DEFAULT 'payment_gateway'
        CHECK (
            tipe_metode IN (
                'payment_gateway',
                'tunai'
            )
        ),

    status_aktif BOOLEAN NOT NULL DEFAULT TRUE
);

-- =========================================================
-- 16. PEMBAYARAN
-- Referensi transaksi pada payment gateway
-- =========================================================

CREATE TABLE pembayaran (
    id_pembayaran BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_transaksi BIGINT NOT NULL,
    id_metode_pembayaran BIGINT NOT NULL,

    provider VARCHAR(50) NOT NULL,
    referensi_provider VARCHAR(150),
    nomor_pesanan_provider VARCHAR(150),

    jumlah_bayar NUMERIC(12,2) NOT NULL
        CHECK (jumlah_bayar >= 0),

    status_pembayaran VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (
            status_pembayaran IN (
                'pending',
                'dibayar',
                'gagal',
                'kedaluwarsa',
                'dibatalkan',
                'dikembalikan'
            )
        ),

    waktu_bayar TIMESTAMPTZ,
    waktu_kedaluwarsa TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_pembayaran_provider_ref
        UNIQUE (provider, referensi_provider),

    CONSTRAINT fk_pembayaran_transaksi
        FOREIGN KEY (id_transaksi)
        REFERENCES transaksi(id_transaksi)
        ON DELETE RESTRICT,

    CONSTRAINT fk_pembayaran_metode
        FOREIGN KEY (id_metode_pembayaran)
        REFERENCES metode_pembayaran(id_metode_pembayaran)
        ON DELETE RESTRICT
);

CREATE INDEX idx_pembayaran_transaksi
    ON pembayaran(id_transaksi);

CREATE INDEX idx_pembayaran_status
    ON pembayaran(status_pembayaran);

-- =========================================================
-- 17. NOTIFIKASI
-- =========================================================

CREATE TABLE notifikasi (
    id_notifikasi BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_user BIGINT NOT NULL,
    judul VARCHAR(150) NOT NULL,
    pesan TEXT NOT NULL,

    status_dibaca BOOLEAN NOT NULL DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notifikasi_user
        FOREIGN KEY (id_user)
        REFERENCES users(id_user)
        ON DELETE CASCADE
);

CREATE INDEX idx_notifikasi_user_baca_tanggal
    ON notifikasi(id_user, status_dibaca, created_at DESC);

-- =========================================================
-- 18. LOG_AKTIVITAS
-- Audit tindakan penting
-- =========================================================

CREATE TABLE log_aktivitas (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_user BIGINT,
    aksi VARCHAR(100) NOT NULL,
    entitas VARCHAR(100),
    id_entitas VARCHAR(100),

    detail JSONB,
    alamat_ip INET,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_log_aktivitas_user
        FOREIGN KEY (id_user)
        REFERENCES users(id_user)
        ON DELETE SET NULL
);

CREATE INDEX idx_log_aktivitas_user_tanggal
    ON log_aktivitas(id_user, created_at DESC);

CREATE INDEX idx_log_aktivitas_entitas
    ON log_aktivitas(entitas, id_entitas);

-- =========================================================
-- 19. PENGATURAN_SISTEM
-- =========================================================

CREATE TABLE pengaturan_sistem (
    id_pengaturan BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    kunci VARCHAR(100) NOT NULL UNIQUE,
    nilai TEXT,
    deskripsi VARCHAR(255),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 20. STOK_LOG
-- Riwayat perubahan stok produk
-- =========================================================

CREATE TABLE stok_log (
    id_stok_log BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    id_varian_produk BIGINT NOT NULL,
    id_user BIGINT,

    jenis_perubahan VARCHAR(30) NOT NULL
        CHECK (
            jenis_perubahan IN (
                'masuk',
                'keluar',
                'penyesuaian',
                'pembatalan'
            )
        ),

    jumlah_perubahan INTEGER NOT NULL,
    stok_sebelum INTEGER NOT NULL CHECK (stok_sebelum >= 0),
    stok_sesudah INTEGER NOT NULL CHECK (stok_sesudah >= 0),

    keterangan VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stok_log_varian
        FOREIGN KEY (id_varian_produk)
        REFERENCES varian_produk(id_varian_produk)
        ON DELETE RESTRICT,

    CONSTRAINT fk_stok_log_user
        FOREIGN KEY (id_user)
        REFERENCES users(id_user)
        ON DELETE SET NULL
);

CREATE INDEX idx_stok_log_varian_tanggal
    ON stok_log(id_varian_produk, created_at DESC);

-- =========================================================
-- TRIGGER UPDATED_AT
-- =========================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_produk_updated_at
BEFORE UPDATE ON produk
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_keranjang_updated_at
BEFORE UPDATE ON keranjang
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_pembayaran_updated_at
BEFORE UPDATE ON pembayaran
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_pengaturan_sistem_updated_at
BEFORE UPDATE ON pengaturan_sistem
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

COMMIT;
