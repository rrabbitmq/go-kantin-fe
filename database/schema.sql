-- Go Kantin — PostgreSQL schema + seed
-- Buat database terlebih dahulu: CREATE DATABASE go_kantin;
-- Lalu: psql -U postgres -d go_kantin -f database/schema.sql

DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS cart_items CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS categories CASCADE;
DROP TABLE IF EXISTS queue_slots CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL,
  student_id    VARCHAR(32) NOT NULL UNIQUE,
  avatar_letter VARCHAR(4) NOT NULL DEFAULT 'F'
);

CREATE TABLE categories (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(80) NOT NULL,
  slug        VARCHAR(80) NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  icon_path   VARCHAR(255) NOT NULL DEFAULT '',
  filter_class VARCHAR(40) NOT NULL DEFAULT 'main-dishes'
);

CREATE TABLE products (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id   INTEGER NOT NULL REFERENCES categories(id),
  name          VARCHAR(120) NOT NULL,
  price         NUMERIC(12, 2) NOT NULL,
  image_path    VARCHAR(255) NOT NULL,
  description   TEXT NOT NULL DEFAULT '',
  ingredients   TEXT NOT NULL DEFAULT '',
  is_vegan      BOOLEAN NOT NULL DEFAULT FALSE,
  rating_count  INTEGER NOT NULL DEFAULT 0,
  is_bestseller BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE cart_items (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  quantity   INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
  note       TEXT NOT NULL DEFAULT ''
);

CREATE TABLE orders (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id),
  order_code      VARCHAR(40) NOT NULL UNIQUE,
  status          VARCHAR(20) NOT NULL DEFAULT 'processing',
  total_amount    NUMERIC(12, 2) NOT NULL DEFAULT 0,
  eta_minutes     INTEGER,
  pickup_label    VARCHAR(120) NOT NULL DEFAULT 'Ambil di Kantin',
  pickup_location VARCHAR(160) NOT NULL DEFAULT 'Kantin JTI • Lantai 8',
  created_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE order_items (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id  INTEGER REFERENCES products(id),
  product_name VARCHAR(120) NOT NULL,
  image_path  VARCHAR(255) NOT NULL DEFAULT '',
  quantity    INTEGER NOT NULL DEFAULT 1,
  unit_price  NUMERIC(12, 2) NOT NULL DEFAULT 0,
  note        TEXT NOT NULL DEFAULT ''
);

CREATE TABLE queue_slots (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_label    VARCHAR(40) NOT NULL,
  slot_value    VARCHAR(40) NOT NULL UNIQUE,
  queue_count   INTEGER NOT NULL DEFAULT 0,
  is_current    BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order    INTEGER NOT NULL DEFAULT 0
);

